export function PlatformLogo({ platform, size = 'md', className = '', mono = false }: PlatformLogoProps) {
  const meta = PLATFORM_META[platform];
  if (!meta) return null;
  const px = SIZE_PX[size];
  const color = mono ? 'currentColor' : BRAND_HEX[platform] ?? 'currentColor';
  const spec = PATHS[platform];

  // Federacy has no standalone SVG mark; render styled wordmark in brand color.
  if (!spec) {
    return (
      <span
        aria-label={meta.label}
        title={meta.label}
        className={`inline-flex items-center justify-center mono font-semibold tracking-tight select-none ${className}`}
        style={{ color, fontSize: `${Math.max(9, px * 0.6)}px`, height: px }}
      >
        {meta.label.toLowerCase()}
      </span>
    );
  }

  return (
    <svg
      role="img"
      aria-label={meta.label}
      xmlns="http://www.w3.org/2000/svg"
      viewBox={spec.viewBox}
      width={px}
      height={px}
      fill={color}
      className={`inline-block shrink-0 ${className}`}
    >
      <title>{meta.label}</title>
      {spec.paths.map((d, i) => (
        <path key={i} d={d} />
      ))}
    </svg>
  );
}
